"""Plan photos: one source of truth, img/plans/bank.json, turned into what the apps use. Run it after changing the bank
(adding or removing a photo is an admin task, per the 7 Nov 2026 spec):

    python tools/plan-photos.py

It writes
  - the PHOTO_BANK block in app.js (between the "PHOTO_BANK" marker comments)
  - app/src/lib/photoFiles.ts (the app's require() list and the same bank)
  - app/assets/plans/*.webp (copies of img/plans/*.webp for the app)
  - the "More plan photos" list in credits.html (between the marker comments), for photos the page doesn't list yet

Each photo in bank.json: k (file img/plans/<k>.webp), cats (the categories whose bank it's in), tags (words and phrases
matched against a plan's description and venue), def (categories it's the default photo of: exactly one per category),
title, by, lic, licUrl, src (the attribution the activity view shows).
Rules for the bank: licence CC0, CC BY or CC BY-SA only (never NC or ND: the apps crop and resize); no identifiable
person; places, food, objects and scenes. Resized copies keep the original licence and attribution.
"""
import html, json, os, re, shutil, sys

WEB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATS = ['fitness', 'movies', 'theatre', 'comedy', 'concerts', 'hangout', 'cafe', 'adventure', 'outdoor', 'errands', 'work', 'selfcare', 'nightlife']
LIC = re.compile(r'^(CC0( 1\.0)?|CC BY(-SA)? [0-9.]+)$', re.I)


def load():
    bank = json.load(open(os.path.join(WEB, 'img/plans/bank.json'), encoding='utf-8'))['photos']
    bad = []
    for p in bank:
        if not LIC.match(p['lic']): bad.append(f"{p['k']}: licence {p['lic']!r} isn't CC0, CC BY or CC BY-SA")
        if not os.path.exists(os.path.join(WEB, 'img/plans', p['k'] + '.webp')): bad.append(f"{p['k']}: no img/plans/{p['k']}.webp")
        if any(c not in CATS for c in p['cats'] + p['def']): bad.append(f"{p['k']}: unknown category")
        if any(c not in p['cats'] for c in p['def']): bad.append(f"{p['k']}: default for a category it isn't in")
    for c in CATS:
        n = [p['k'] for p in bank if c in p['def']]
        if len(n) != 1: bad.append(f'{c}: needs exactly one default photo, has {n}')
    if bad: sys.exit('\n'.join(bad))
    return bank


def between(text, start, end, body):
    i, j = text.index(start), text.index(end)
    return text[:i + len(start)] + body + text[j:]


def main():
    bank = load()
    rows = [[p['k'], p['cats'], p['tags'], p['def'], p['title'], p['by'], p['lic'], p['licUrl'], p['src']] for p in bank]
    # website
    js = os.path.join(WEB, 'app.js')
    s = open(js, encoding='utf-8').read()
    body = '\nconst PHOTO_BANK=' + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + \
           '.map(([k,cats,tags,def,title,by,lic,licUrl,src])=>({k,cats,tags,def,title,by,lic,licUrl,src}));\n'
    s = between(s, '/* PHOTO_BANK start: generated by tools/plan-photos.py from img/plans/bank.json */', '/* PHOTO_BANK end */', body)
    open(js, 'w', encoding='utf-8', newline='').write(s)
    # app
    assets = os.path.join(WEB, 'app/assets/plans')
    os.makedirs(assets, exist_ok=True)
    for p in bank: shutil.copyfile(os.path.join(WEB, 'img/plans', p['k'] + '.webp'), os.path.join(assets, p['k'] + '.webp'))
    ts = ['/* Generated by web/tools/plan-photos.py from web/img/plans/bank.json (the same photos as web/img/plans). Don\'t edit by hand. */',
          'export const PHOTOS = {']
    ts += [f"  {p['k']}: require('../../assets/plans/{p['k']}.webp')," for p in bank]
    ts += ['} as const;', 'export type PhotoKey = keyof typeof PHOTOS;',
           'export type BankPhoto = { k: PhotoKey; cats: string[]; tags: string[]; def: string[]; title: string; by: string; lic: string; licUrl: string; src: string };',
           'export const BANK: BankPhoto[] = ' + json.dumps(bank, ensure_ascii=False, indent=1).replace('\n', '\n') + ' as BankPhoto[];', '']
    open(os.path.join(WEB, 'app/src/lib/photoFiles.ts'), 'w', encoding='utf-8', newline='').write('\n'.join(ts))
    # credits page: photos it doesn't list yet
    ch = os.path.join(WEB, 'credits.html')
    c = open(ch, encoding='utf-8').read()
    start, end = '<!-- MORE_PLAN_PHOTOS start: generated by tools/plan-photos.py -->', '<!-- MORE_PLAN_PHOTOS end -->'
    outside = c[:c.index(start)] + c[c.index(end):]
    li = []
    for p in bank:
        if f"img/plans/{p['k']}.webp" in outside: continue
        e = lambda x: html.escape(x, quote=True)
        li.append(f'      <li><img src="img/plans/{e(p["k"])}.webp" alt="{e(p["title"])}" loading="lazy" width="96" height="64">\n'
                  f'        <div><b>{e(p["title"])}</b><br><span class="mute">{e(p["by"])} · <a href="{e(p["licUrl"])}" rel="license noopener" target="_blank">{e(p["lic"])}</a> ·\n'
                  f'        <a href="{e(p["src"])}" rel="noopener" target="_blank">source</a></span></div></li>')
    body = '\n    <h3>More plan photos</h3>\n    <ul class="pl">\n' + '\n'.join(li) + '\n    </ul>\n    ' if li else '\n    '
    open(ch, 'w', encoding='utf-8', newline='').write(between(c, start, end, body))
    print(f'{len(bank)} photos; {len(li)} listed under "More plan photos" in credits.html')


if __name__ == '__main__':
    main()
